// Generate the pages that would otherwise drift.
//
// The platform matrix is a fact about the release workflow, not prose. A docs
// page claiming a build that is never published is worse than no page, so it
// is derived from .github/workflows/release.yml rather than hand-maintained.
// Edit the workflow; this file follows.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const out = join(here, '..', 'src', 'content', 'docs', 'reference');

const workflow = readFileSync(
  join(repo, '.github', 'workflows', 'release.yml'),
  'utf8',
);

// Each matrix entry starts with `- rid:` and carries runner, target and an
// optional `also:` alias. Parsed by hand to stay dependency-free; anything
// that no longer matches fails the build instead of publishing an empty table.
const builds = [];
let current = null;
for (const line of workflow.split('\n')) {
  const start = line.match(/^\s*-\s+rid:\s*(\S+)/);
  if (start) {
    current = { rid: start[1] };
    builds.push(current);
    continue;
  }
  const field = line.match(/^\s+(runner|target|also):\s*(\S+)/);
  if (current && field) {
    current[field[1]] = field[2];
  } else if (current && /^\s*-\s/.test(line)) {
    current = null;
  }
}
if (builds.length === 0 || builds.some((b) => !b.runner || !b.target)) {
  throw new Error(
    'could not read the build matrix from release.yml — the workflow changed ' +
      'shape, so this generator needs updating rather than the docs being ' +
      'written by hand',
  );
}

const rows = builds
  .map(
    (b) =>
      `| \`${b.rid}\`${b.also ? ` (also \`${b.also}\`)` : ''} | \`${b.target}\` | \`${b.runner}\` |`,
  )
  .join('\n');

mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, 'platforms.mdx'),
  `---
title: Platforms
description: Where dv runs, and which .NET SDKs it can install there.
---

{/* Generated by docs/scripts/generate.mjs — edit .github/workflows/release.yml, not this file. */}

dv installs whatever Microsoft publishes for the machine it runs on. It names
platforms the way Microsoft's release metadata does — by **runtime
identifier** — so the SDK it downloads is always the one built for this
operating system and processor:

| Machine | Runtime identifier |
|---|---|
| macOS, Apple Silicon | \`osx-arm64\` |
| macOS, Intel | \`osx-x64\` |
| Linux (glibc), x64 / Arm64 | \`linux-x64\` / \`linux-arm64\` |
| Linux (musl — Alpine), x64 / Arm64 | \`linux-musl-x64\` / \`linux-musl-arm64\` |
| Windows, x64 / Arm64 | \`win-x64\` / \`win-arm64\` |

musl is detected from its dynamic loader, because a glibc SDK on Alpine fails
with a "not found" for a binary that plainly exists. Set \`DV_PLATFORM\` to
override detection — useful for testing, not for running an SDK built for
another machine.

Which SDK versions exist for each identifier is Microsoft's decision, not
dv's: \`dv list --remote\` shows exactly what is published for this machine.

## The dv client

dv itself is one binary with no runtime dependencies, built for every
platform below on a native runner:

| Platform | Rust target | Runner |
|---|---|---|
${rows}

Linux builds link **musl** statically, so one binary runs on any
distribution, glibc or musl, with no version floor. The Windows x64 build uses
the GNU target, which links only DLLs Windows ships.

## Windows

SDKs are published as \`.zip\` archives on Windows, and shims are \`.cmd\`
files, because Windows resolves a bare command only through \`PATHEXT\` and a
symlink needs privileges most accounts do not have. Install roots are built
from hard links, which NTFS supports for every user.

dv's state lives in \`%LOCALAPPDATA%\\dv\`.
`,
);

console.log(`generated platforms.mdx (${builds.length} client builds)`);
