//! Shims: real files on `PATH` that delegate resolution back to dv.
//!
//! This is the whole correctness story. `dotnet` must resolve correctly
//! **outside an interactive shell** — editors, language servers, CI runners,
//! git hooks and GUI apps inherit `PATH` and nothing else. A shell hook only
//! ever fires in an interactive shell, so anything launched outside one would
//! silently fall through to a system-wide `dotnet`, with no error.
//!
//! Every generated shim carries a marker line. A version manager that deletes
//! something it did not create is unforgivable, and file identity is the only
//! reliable way to tell a dv shim from a file the user put there.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use crate::installs;
use crate::paths;
use crate::resolve;

/// Present in every generated shim; nothing without it is ever removed.
pub const MARKER: &str = "# managed-by: dv";

/// The same marker as a batch-file comment, for the `.cmd` shims on Windows.
const CMD_MARKER: &str = "rem managed-by: dv";

/// Commands dv shims when an installed SDK provides them. `dnx`, the tool
/// runner that ships from .NET 10, is a script that calls the `dotnet` beside
/// it, so it has to come from the resolved root too.
pub const SHIMMED: &[&str] = &["dotnet", "dnx"];

/// The file a command's shim lives in.
///
/// Windows only resolves a bare command to a file whose extension is listed
/// in `PATHEXT`, so a shim called just `dotnet` would be invisible there — and
/// a symlink needs privileges most accounts do not have. A `.cmd` wrapper is
/// the one shape that always works.
pub fn shim_file(command: &str) -> String {
    if cfg!(windows) {
        format!("{command}.cmd")
    } else {
        command.to_string()
    }
}

pub fn shim_body(dv: &Path, command: &str) -> String {
    #[cfg(not(windows))]
    return sh_shim_body(dv, command);
    #[cfg(windows)]
    return cmd_shim_body(dv, command);
}

#[cfg(any(not(windows), test))]
fn sh_shim_body(dv: &Path, command: &str) -> String {
    format!(
        "#!/bin/sh\n\
         {MARKER}\n\
         # generated by dv — edits are overwritten on the next install\n\
         exec {} run {command} \"$@\"\n",
        quote(&dv.to_string_lossy())
    )
}

/// Single-quote for `/bin/sh`. Shim paths can contain spaces, and an unquoted
/// interpreter path turns the first space into an argument boundary.
#[cfg(any(not(windows), test))]
fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

/// The batch equivalent: forward every argument, and leave with the exit code
/// the command produced.
///
/// A Windows path cannot contain a double quote, so quoting it is enough to
/// keep spaces together. A percent sign is legal in a path and would start a
/// variable expansion, so it is doubled.
#[cfg(any(windows, test))]
fn cmd_shim_body(dv: &Path, command: &str) -> String {
    format!(
        "@echo off\r\n\
         {CMD_MARKER}\r\n\
         rem generated by dv - edits are overwritten on the next install\r\n\
         \"{}\" run {command} %*\r\n\
         exit /b %ERRORLEVEL%\r\n",
        dv.to_string_lossy().replace('%', "%%")
    )
}

/// Write a shim for every command any installed SDK provides, and remove
/// dv-owned shims for commands that no longer exist anywhere.
pub fn sync() -> Result<Vec<String>> {
    let dir = paths::shims_dir()?;
    paths::ensure_dir(&dir)?;
    let dv = std::env::current_exe().context("could not determine dv's own path")?;

    let mut wanted: Vec<String> = Vec::new();
    for version in installs::installed()? {
        for command in installs::commands(&version)? {
            if !wanted.contains(&command) {
                wanted.push(command);
            }
        }
    }
    // With only runtimes installed, the combined root still has a host that
    // runs apps, and `dotnet app.dll` should reach it.
    if !wanted.iter().any(|command| command == "dotnet")
        && crate::roots::host(&paths::combined_root()?).is_file()
    {
        wanted.push("dotnet".to_string());
    }
    wanted.sort();

    for command in &wanted {
        write_shim(&dir.join(shim_file(command)), &shim_body(&dv, command))?;
    }
    remove_orphans(&dir, &wanted)?;
    Ok(wanted)
}

fn write_shim(path: &Path, body: &str) -> Result<()> {
    if let Ok(existing) = std::fs::read_to_string(path)
        && existing == body
    {
        return Ok(());
    }
    if path.exists() && !is_dv_shim(path)? {
        // Someone else owns this name here. Leave it alone and let doctor say so.
        return Ok(());
    }
    std::fs::write(path, body).with_context(|| format!("could not write {}", path.display()))?;
    paths::make_executable(path)
}

fn remove_orphans(dir: &Path, wanted: &[String]) -> Result<()> {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(_) => return Ok(()),
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if wanted.iter().any(|command| shim_file(command) == name) {
            continue;
        }
        if is_dv_shim(&path)? {
            std::fs::remove_file(&path)
                .with_context(|| format!("could not remove {}", path.display()))?;
        }
    }
    Ok(())
}

pub fn is_dv_shim(path: &Path) -> Result<bool> {
    let Ok(body) = std::fs::read_to_string(path) else {
        return Ok(false);
    };
    Ok(body
        .lines()
        .take(5)
        .any(|line| matches!(line.trim(), MARKER | CMD_MARKER)))
}

/// Whether the shim directory is on `PATH`, and whether anything shadows it.
pub struct PathStatus {
    pub shims: PathBuf,
    pub on_path: bool,
    /// Entries before the shim directory that also provide the command.
    pub shadowed_by: Vec<PathBuf>,
}

pub fn path_status(command: &str) -> Result<PathStatus> {
    let shims = paths::shims_dir()?;
    let entries = crate::lookup::entries();

    let position = entries.iter().position(|entry| same_dir(entry, &shims));
    let before = match position {
        Some(index) => &entries[..index],
        None => &entries[..],
    };
    let shadowed_by = before
        .iter()
        .filter_map(|dir| crate::lookup::find_in(dir, command))
        .collect();

    Ok(PathStatus {
        shims,
        on_path: position.is_some(),
        shadowed_by,
    })
}

/// Whether two `PATH` entries name the same directory. Windows paths are
/// case-insensitive, and nothing guarantees `PATH` spells the shim directory
/// the way dv does.
pub fn same_dir(a: &Path, b: &Path) -> bool {
    if cfg!(windows) {
        let fold = |path: &Path| PathBuf::from(path.to_string_lossy().to_lowercase());
        fold(a) == fold(b)
    } else {
        a == b
    }
}

/// What `dv init <shell>` emits.
///
/// Prepending the shims is the point: a shim directory placed after
/// `/usr/local/share/dotnet` or a package manager's prefix is silently
/// shadowed.
///
/// `DOTNET_ROOT` is set to the combined root, which holds every installed SDK
/// and runtime. Global tools (`dotnet tool install -g`) and apps built with an
/// app host find their runtime through it, and editors that ask for "the .NET
/// install" get one that sees everything dv installed. Commands run through a
/// shim get their own, narrower root regardless.
pub fn init_snippet(shell: &str, shims: &Path, combined: &Path) -> String {
    let shims = shims.to_string_lossy().to_string();
    let combined = combined.to_string_lossy().to_string();
    match shell {
        "powershell" | "pwsh" => {
            let shims = shims.replace('\'', "''");
            let combined = combined.replace('\'', "''");
            format!(
                "# dv\nif (($env:PATH -split [IO.Path]::PathSeparator) -notcontains '{shims}') {{\n    \
                 $env:PATH = '{shims}' + [IO.Path]::PathSeparator + $env:PATH\n}}\n\
                 $env:DOTNET_ROOT = '{combined}'\n"
            )
        }
        "fish" => format!(
            "# dv\nif not contains '{shims}' $PATH\n    set -gx PATH '{shims}' $PATH\nend\n\
             set -gx DOTNET_ROOT '{combined}'\n",
            shims = shims.replace('\'', "\\'"),
            combined = combined.replace('\'', "\\'"),
        ),
        _ => format!(
            "# dv\ncase \":$PATH:\" in\n  *\":{shims}:\"*) ;;\n  *) PATH=\"{shims}:$PATH\" ;;\nesac\n\
             export PATH\nDOTNET_ROOT=\"{combined}\"\nexport DOTNET_ROOT\n"
        ),
    }
}

/// The optional `cd`-time hook, appended to `dv init <shell> --hook`.
///
/// Correctness never depends on this. The shims already resolve the right SDK
/// for every process, interactive or not; the hook only moves resolution from
/// per-command to per-directory. It is opt-in for that reason — a shell hook
/// that goes wrong takes the whole shell with it, and nothing here needs it
/// to be right.
///
/// It exports `DV_DOTNET_VERSION`, which outranks every file-based rule, and
/// that makes three things load-bearing.
///
/// It must run once at startup, not only on `cd`: a new shell inherits an
/// exported value from whatever directory its parent was in, and without an
/// initial run that stale value silently outranks the new shell's own
/// `global.json`.
///
/// It must clear the variable when nothing pins a version, so the fallback
/// stays dynamic instead of freezing at whatever resolved once.
///
/// And it must not read back what it wrote. Resolution treats the environment
/// as the highest-priority pin, so a hook that resolves with its own export
/// still set sees it every time and re-pins the same value forever — leave a
/// pinned directory and the version follows you out. The hook therefore
/// tracks what it set in `_DV_HOOK_SET` and clears its own export before
/// resolving. A value it does not recognize was set by hand and is left
/// strictly alone.
pub fn hook_snippet(shell: &str, dv: &Path) -> String {
    let dv = dv.to_string_lossy().to_string();
    let var = resolve::ENVIRONMENT;
    match shell {
        "fish" => format!(
            "\n# dv: switch on cd (optional — the shims work without it)\n\
             function _dv_hook --on-variable PWD\n    \
                 if set -q {var}\n        \
                     if test \"${var}\" != \"$_DV_HOOK_SET\"\n            \
                         return\n        \
                     end\n    \
                 end\n    \
                 set -e {var}\n    \
                 set -l resolved ('{dv}' resolve --pinned-only 2>/dev/null)\n    \
                 if test -n \"$resolved\"\n        \
                     set -gx {var} $resolved\n        \
                     set -gx _DV_HOOK_SET $resolved\n    \
                 else\n        \
                     set -e _DV_HOOK_SET\n    \
                 end\n\
             end\n\
             _dv_hook\n",
            dv = dv.replace('\'', "\\'"),
        ),
        _ => format!(
            "\n# dv: switch on cd (optional — the shims work without it)\n\
             _dv_hook() {{\n  \
                 if [ -n \"${{{var}-}}\" ] && \
                    [ \"${{{var}-}}\" != \"${{_DV_HOOK_SET-}}\" ]; then\n    \
                     return 0\n  \
                 fi\n  \
                 unset {var}\n  \
                 _dv_resolved=\"$({dv} resolve --pinned-only 2>/dev/null)\"\n  \
                 if [ -n \"$_dv_resolved\" ]; then\n    \
                     {var}=\"$_dv_resolved\"; export {var}\n    \
                     _DV_HOOK_SET=\"$_dv_resolved\"; export _DV_HOOK_SET\n  \
                 else\n    \
                     unset _DV_HOOK_SET\n  \
                 fi\n  \
                 unset _dv_resolved\n\
             }}\n\
             if [ -n \"${{ZSH_VERSION-}}\" ]; then\n  \
                 autoload -Uz add-zsh-hook 2>/dev/null && add-zsh-hook chpwd _dv_hook\n\
             elif [ -n \"${{BASH_VERSION-}}\" ]; then\n  \
                 case \"${{PROMPT_COMMAND-}}\" in\n    \
                     *_dv_hook*) ;;\n    \
                     *) PROMPT_COMMAND=\"_dv_hook${{PROMPT_COMMAND:+;$PROMPT_COMMAND}}\" ;;\n  \
                 esac\n\
             fi\n\
             _dv_hook\n",
            dv = quote_posix(&dv),
        ),
    }
}

fn quote_posix(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shim_execs_dv_and_forwards_arguments() {
        let body = sh_shim_body(Path::new("/opt/dv/bin/dv"), "dotnet");
        assert!(body.starts_with("#!/bin/sh\n"));
        assert!(body.contains(MARKER));
        assert!(body.contains("exec '/opt/dv/bin/dv' run dotnet \"$@\"\n"));
    }

    #[test]
    fn paths_with_spaces_stay_one_word() {
        let body = sh_shim_body(Path::new("/Users/a b/Library/dv"), "dnx");
        assert!(body.contains("exec '/Users/a b/Library/dv' run dnx \"$@\""));
    }

    #[test]
    fn single_quotes_in_a_path_do_not_break_out() {
        let body = sh_shim_body(Path::new("/home/o'brien/dv"), "dotnet");
        assert!(body.contains(r"exec '/home/o'\''brien/dv' run dotnet"));
    }

    #[test]
    fn a_cmd_shim_forwards_arguments_and_the_exit_code() {
        let body = cmd_shim_body(Path::new(r"C:\Users\a b\.local\bin\dv.exe"), "dotnet");
        assert!(body.starts_with("@echo off\r\n"));
        assert!(body.contains(CMD_MARKER));
        assert!(body.contains("\"C:\\Users\\a b\\.local\\bin\\dv.exe\" run dotnet %*\r\n"));
        assert!(body.ends_with("exit /b %ERRORLEVEL%\r\n"));
    }

    #[test]
    fn a_percent_sign_in_a_path_is_not_a_variable() {
        let body = cmd_shim_body(Path::new(r"C:\100%\dv.exe"), "dotnet");
        assert!(body.contains("\"C:\\100%%\\dv.exe\" run dotnet %*"));
    }

    #[test]
    fn identifies_its_own_files_and_nobody_elses() {
        let dir = tempfile::tempdir().unwrap();
        let ours = dir.path().join("dotnet");
        std::fs::write(&ours, sh_shim_body(Path::new("/opt/dv"), "dotnet")).unwrap();
        let ours_cmd = dir.path().join("dotnet.cmd");
        std::fs::write(&ours_cmd, cmd_shim_body(Path::new(r"C:\dv.exe"), "dotnet")).unwrap();
        let theirs = dir.path().join("dotnet-theirs");
        std::fs::write(
            &theirs,
            "#!/bin/sh\nexec /usr/local/share/dotnet/dotnet \"$@\"\n",
        )
        .unwrap();

        assert!(is_dv_shim(&ours).unwrap());
        assert!(is_dv_shim(&ours_cmd).unwrap());
        assert!(!is_dv_shim(&theirs).unwrap());
        assert!(!is_dv_shim(&dir.path().join("missing")).unwrap());
    }

    #[test]
    fn the_hook_runs_at_startup_and_clears_a_stale_override() {
        for shell in ["zsh", "fish"] {
            let hook = hook_snippet(shell, Path::new("/opt/dv"));
            assert!(
                hook.trim_end().ends_with("_dv_hook"),
                "{shell}: must run once at startup, or an inherited \
                 DV_DOTNET_VERSION outranks the new shell's own global.json"
            );
            assert!(
                hook.contains("unset DV_DOTNET_VERSION")
                    || hook.contains("set -e DV_DOTNET_VERSION"),
                "{shell}: must clear the override when nothing pins a version"
            );
            assert!(
                hook.contains("_DV_HOOK_SET"),
                "{shell}: must track what it set, or resolution reads back its own \
                 export as a pin and the version follows you out of the directory"
            );
        }
    }

    #[test]
    fn init_snippets_are_idempotent_prepend_and_set_dotnet_root() {
        let shims = Path::new("/home/dev/.local/share/dv/shims");
        let combined = Path::new("/home/dev/.local/share/dv/dotnet");

        let posix = init_snippet("zsh", shims, combined);
        assert!(posix.contains("case \":$PATH:\""), "idempotent: {posix}");
        assert!(
            posix.contains("PATH=\"/home/dev/.local/share/dv/shims:$PATH\""),
            "prepends: {posix}"
        );
        assert!(
            posix.contains("DOTNET_ROOT=\"/home/dev/.local/share/dv/dotnet\""),
            "{posix}"
        );

        let powershell = init_snippet(
            "powershell",
            Path::new(r"C:\Users\o'brien\.dv\shims"),
            Path::new(r"C:\Users\o'brien\.dv\dotnet"),
        );
        assert!(
            powershell.contains("-notcontains"),
            "idempotent: {powershell}"
        );
        assert!(
            powershell.contains(
                r"$env:PATH = 'C:\Users\o''brien\.dv\shims' + [IO.Path]::PathSeparator + $env:PATH"
            ),
            "prepends: {powershell}"
        );
        assert!(powershell.contains(r"$env:DOTNET_ROOT = 'C:\Users\o''brien\.dv\dotnet'"));

        let fish = init_snippet("fish", shims, combined);
        assert!(fish.contains("if not contains"), "idempotent: {fish}");
        assert!(
            fish.contains("set -gx PATH '/home/dev/.local/share/dv/shims' $PATH"),
            "prepends: {fish}"
        );
        assert!(fish.contains("set -gx DOTNET_ROOT '/home/dev/.local/share/dv/dotnet'"));
    }
}
